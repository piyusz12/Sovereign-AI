# ── Authentication ────────────────────────────────────────────────────────────


class LoginRequest(BaseModel):
    """Login request body."""
    username: str
    password: str


@router.post("/auth/login")
async def login(request: LoginRequest):
    """
    Authenticate with username/password and receive a JWT token.
    All authentication is local — no external identity providers.
    """
    from backend.security.auth import authenticate_user, create_access_token

    user = authenticate_user(request.username, request.password)
    if not user:
        raise HTTPException(status_code=401, detail="Invalid credentials")

    token = create_access_token(
        data={"sub": user.username, "role": user.role}
    )
    return {
        "access_token": token,
        "token_type": "bearer",
        "user": {
            "username": user.username,
            "role": user.role,
            "department": user.department,
        },
    }


@router.get("/auth/me")
async def get_current_user(token: str = ""):
    """
    Decode a JWT token and return the current user.
    Pass the token as a query parameter for simplicity in Phase 3.
    """
    from backend.security.auth import decode_token, DEMO_USERS, User

    if not token:
        raise HTTPException(status_code=401, detail="Token required")

    token_data = decode_token(token)
    if not token_data or not token_data.username:
        raise HTTPException(status_code=401, detail="Invalid or expired token")

    user_data = DEMO_USERS.get(token_data.username)
    if not user_data:
        raise HTTPException(status_code=404, detail="User not found")

    return {
        "username": user_data["username"],
        "role": user_data["role"],
        "department": user_data["department"],
    }


